// Раньше все экраны "главного" раздела приложения (каркас с нижней
// навигацией, услуги, корзина, форма "Спила", "Мои заказы") жили в одном
// большом файле base.dart. Для удобства навигации и отладки он разделён
// на отдельные модули:
//
// - home_shell.dart        — каркас (нижняя навигация + корзина)
// - services_page.dart     — вкладка "Услуги" и карточки услуг
// - tree_cutting_modal.dart — форма оформления "Спила"
// - my_orders_page.dart    — вкладка "Мои заказы"
// - order_summary.dart     — модель одного заказа + парсинг координат
// - session_utils.dart     — выход на экран входа при истёкшей сессии
// - format_utils.dart      — форматирование даты/времени
//
// Сам base.dart оставлен как индекс (export), чтобы существующий импорт
// `import 'home/base.dart';` (см. main.dart) продолжал работать без
// изменений — при желании его можно заменить на прямые импорты нужных
// файлов.
export 'home_shell.dart';
export 'my_orders_page.dart';
export 'services_page.dart';
